/**
 * Las hojas donde CADA FILA es un movimiento del negocio. Enumeradas a mano y revisadas una
 * por una: es la lista que no puede encogerse sin que alguien lo decida a propósito.
 *
 * No se deriva de `clase === 'financial'`, y esa distinción importa: "Resumen" de Kapel
 * clasifica como financiera —tiene Mes, Costo, Venta— pero es un RESUMEN mensual, no
 * movimientos. Descartarla es correcto; sumarla duplicaría contra "Racum 2025", que es de
 * donde salen esas mismas ventas fila por fila.
 */
const HOJAS_DE_MOVIMIENTOS = [
  'Ventas_Diarias',
  'Costos_Operativos',
  'Ventas',
  'OrdenesCompra',
  'LineasOC',
  'Racum 2025',
  'Reporte mensual 2026',
] as const;

describe('lo que el corpus garantiza en conjunto', () => {
  test('NINGUNA hoja de movimientos se descarta', () => {
    /*
     * La garantía que más importa, y la de fallo más caro: descartar una hoja de movimientos
     * pierde contabilidad del cliente EN SILENCIO — no aparece en su dashboard y nadie lo
     * nota. Descartar de menos solo cuesta lo que ya cuesta.
     */
    const perdidas = CORPUS.filter(
      (h) =>
        (HOJAS_DE_MOVIMIENTOS as readonly string[]).includes(h.hoja) &&
        (h.forma === 'reporte' || h.clase === 'catalog'),
    );
    expect(perdidas.map((h) => `${h.archivo}/${h.hoja}`)).toEqual([]);
  });

  test('las siete hojas de movimientos siguen estando en el corpus', () => {
    // Si una desaparece del corpus, la garantía de arriba pasa a ser vacua sin que nadie lo
    // note: un test que no cubre nada siempre está verde.
    for (const hoja of HOJAS_DE_MOVIMIENTOS) {
      expect(CORPUS.some((h) => h.hoja === hoja)).toBe(true);
    }
  });

  test('las hojas con títulos arriba se reconocen', () => {
    const conTitulos = CORPUS.filter((h) => h.encabezado > 0);
    expect(conTitulos.map((h) => h.hoja)).toContain('Reporte mensual 2026');
    expect(conTitulos.map((h) => h.hoja)).toContain('Resumen');
  });

  test('los layouts de reporte se atrapan, y son solo de Kapel', () => {
    // Los tres archivos son de rubros distintos; que TODOS los reportes vengan del mismo dice
    // que la detección responde a la forma del archivo y no a un sesgo del detector.
    const reportes = CORPUS.filter((h) => h.forma === 'reporte');
    expect(reportes.length).toBeGreaterThanOrEqual(4);
    expect(new Set(reportes.map((h) => h.archivo))).toEqual(new Set(['kapel']));
  });

  test('los catálogos se descartan en los dos volcados operativos', () => {
    // Cafetería y Joyería son volcados completos de sistema: sus catálogos no deben pagarse.
    for (const archivo of ['cafeteria', 'joyeria'] as const) {
      expect(
        CORPUS.filter((h) => h.archivo === archivo && h.clase === 'catalog').length,
      ).toBeGreaterThan(0);
    }
  });
});
